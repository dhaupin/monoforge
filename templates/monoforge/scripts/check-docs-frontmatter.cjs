#!/usr/bin/env node
/**
 * Docs frontmatter gate (pass 153).
 *
 * docs/advanced/style.md requires every page to carry all 5 frontmatter
 * fields (version, permalink, layout, title, nav_order) -- but until now
 * NOTHING enforced it, and pass 151 found 2 of 118 pages missing
 * `layout:` with a real consequence: docs/_config.yml has no `defaults`
 * block, so Jekyll renders a layout-less page as raw HTML with no site
 * chrome. Silent breakage, invisible to every regex gate until now.
 *
 * Checks every markdown page under docs/:
 *   - all 5 style.md-required fields present and non-empty
 *   - permalink is absolute-ish (starts with /) -- the site links by it
 *   - nav_order is an integer
 *   - every field value is a VALID YAML scalar. A regex scan for `key: value`
 *     says nothing about whether YAML parses: an unquoted value carrying a
 *     colon-space (`description: slots: generated by the factory`) is a YAML
 *     error, and Jekyll then drops the WHOLE frontmatter block -- no layout,
 *     no head injection, a page that renders without its own chrome. That bug
 *     bit monoforge's docs/index.md and shipped green (rule #3: caught twice,
 *     it becomes a gate). Dependency-free on purpose: a stamped repo has no
 *     install step for this gate to lean on.
 *
 * NOTE: the version field is PRESENCE-only. style.md defines it as
 * "version introduced", which legitimately differs from package.json
 * (e.g. "0.8.5" pages on a 0.8.6 package); equality would be a false
 * positive. Drift of the *current* version is caught in judgment reads.
 *
 * Exit 1 on any violation, evidence inline.
 */
const fs = require('fs');
const path = require('path');

// --root <dir> checks a tree other than this one (tests + adopters),
// the family gate convention (flowforge lib/root.cjs).
const rootArg = process.argv.indexOf('--root');
const ROOT = rootArg !== -1 ? path.resolve(process.argv[rootArg + 1]) : path.resolve(__dirname, '..');
const DOCS = path.join(ROOT, 'docs');

const REQUIRED = ['version', 'permalink', 'layout', 'title', 'nav_order'];

const problems = [];
let pages = 0;

// Is a frontmatter scalar valid plain YAML (the subset Jekyll's frontmatter
// parser accepts for these fields)? Quoted and block scalars are always
// fine; an unquoted scalar must not open a nested mapping (`: `), start a
// comment (` #`), or begin with an indicator that changes its type. This is
// the dependency-free stand-in for a YAML parse -- enough to catch the exact
// class that shipped: an unquoted value carrying a colon-space.
function scalarProblem(raw) {
    const v = raw.trim();
    if (!v) return 'is empty';
    const q = v[0];
    if (q === '"' || q === "'") {
        if (v.length < 2 || v[v.length - 1] !== q) return 'has an unterminated quote';
        return null;
    }
    if (/^[|>]/.test(v)) return null; // block scalar
    if (/:\s/.test(v)) return 'is unquoted and contains a colon-space, which YAML reads as a nested mapping (quote it, or fold the value)';
    if (/\s#/.test(v)) return 'is unquoted and contains " #", which YAML reads as a comment (quote it)';
    if (/^[&*?,[\]{}%!@`>|]/.test(v)) return `starts with a YAML indicator (${v[0]}); quote it`;
    return null;
}
(function walk(d) {
    for (const f of fs.readdirSync(d, { withFileTypes: true })) {
        const p = d + '/' + f.name;
        if (f.isDirectory() && f.name !== '_data' && f.name !== '_layouts' && f.name !== '_plugins') walk(p);
        else if (f.name.endsWith('.md')) {
            pages++;
            const rel = path.relative(ROOT, p);
            const text = fs.readFileSync(p, 'utf8');
            const fm = text.match(/^---\n([\s\S]*?)\n---/);
            if (!fm) { problems.push(`${rel}: no frontmatter block`); continue; }
            const block = fm[1];
            for (const field of REQUIRED) {
                const m = block.match(new RegExp(`^${field}:\\s*(.*\\S)`, 'm'));
                if (!m) { problems.push(`${rel}: missing frontmatter field "${field}"`); continue; }
                const val = m[1].trim();
                if (!val || val === '""' || val === "''") {
                    problems.push(`${rel}: frontmatter field "${field}" is empty`);
                    continue;
                }
                if (field === 'permalink' && !val.startsWith('/')) {
                    problems.push(`${rel}: permalink "${val}" should start with / (site links by it)`);
                }
                if (field === 'nav_order' && !/^-?\d+$/.test(val)) {
                    problems.push(`${rel}: nav_order "${val}" is not an integer`);
                }
            }
            // Scalar validity across EVERY top-level field, not only the
            // required ones: monoforge's bug landed in `description`, which a
            // variant gate that did not require it would have scanned past.
            // Required-ness must not gate this check.
            for (const line of block.split('\n')) {
                if (/^\s/.test(line)) continue; // nested value or continuation
                const mm = line.match(/^([A-Za-z_][\w-]*):\s*(.*\S)\s*$/);
                if (!mm) continue;
                const err = scalarProblem(mm[2]);
                if (err) problems.push(`${rel}: frontmatter field "${mm[1]}" ${err}`);
            }
        }
    }
})(DOCS);

if (problems.length) {
    console.error(`FRONTMATTER: FAIL (${problems.length} issue${problems.length === 1 ? '' : 's'} in ${pages} pages)`);
    for (const p of problems) console.error('  ' + p);
    process.exit(1);
}
console.log(`FRONTMATTER: PASS (${pages} pages, all ${REQUIRED.length} fields + format checks)`);
